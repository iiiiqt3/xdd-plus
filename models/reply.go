// 获取用户QQ昵称（关键修改2：同步返回昵称）
func GetQQNickname(userID string) string {
    // 创建用于接收响应的通道
    replyChan := make(chan []byte, 1)
    // 构造请求体
    reqData := struct {
        Action string `json:"action"`
        Params struct {
            UserID string `json:"user_id"`
        } `json:"params"`
        Echo string `json:"echo"`
    }{
        Action: "get_stranger_info",
        Params: struct {
            UserID string `json:"user_id"`
        }{UserID: userID},
        Echo: "get_nickname_" + userID, // 用userID区分不同请求的响应
    }
    // 序列化请求
    marshal, err := json.Marshal(reqData)
    if err != nil {
        return "昵称获取失败（请求序列化错误）"
    }
    // 发送请求
    msgchan <- marshal

    // 等待响应（超时5秒）
    var resp []byte
    select {
    case resp = <-replyChan: // 假设响应会通过replyChan返回（需配合消息框架的响应分发）
    case <-time.After(5 * time.Second):
        return "昵称获取超时"
    }

    // 解析响应
    var result struct {
        Data struct {
            Nickname string `json:"nickname"` // 提取昵称
        } `json:"data"`
        Retcode int `json:"retcode"` // 状态码（0为成功）
    }
    if err := json.Unmarshal(resp, &result); err != nil {
        return "昵称解析失败"
    }
    if result.Retcode != 0 {
        return "获取失败（错误码：" + strconv.Itoa(result.Retcode) + "）"
    }
    return result.Data.Nickname // 返回解析到的昵称
}
