func SendQQMsg(msg QQMessage) {
	// 自动补全message_type：为空时根据GroupID/UserId判断
	if msg.QQMsg.MessageType == "" {
		if msg.QQMsg.GroupID > 0 {
			msg.QQMsg.MessageType = "group"
		} else if msg.QQMsg.UserId > 0 {
			msg.QQMsg.MessageType = "private"
		} else {
			Error("SendQQMsg: 无法确定消息类型，group_id和user_id均为空")
			return
		}
	}

	marshal, err := json.Marshal(msg)
	if err != nil {
		Error("序列化QQ消息失败：", err)
		return
	}
	Bot().Infof(string(marshal))
	msgchan <- marshal
}




