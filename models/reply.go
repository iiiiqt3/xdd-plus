func TransferRequest(toWxid string, transferid string, money string) error {
	// 构造请求 URL
	url := qxHttpAPIURL()

	// 构造请求数据
	requestBody := map[string]interface{}{
		"type": "Q0016",
		"data": map[string]string{
			"wxid":       toWxid,
			"transferid": transferid,
		},
	}
	payload, err := json.Marshal(requestBody)
	if err != nil {
		Error("构造请求体失败:", err)
		return err
	}

	// 发起 POST 请求
	req := httplib.Post(url)
	req.Header("Content-Type", "application/json") // 设置请求头
	req.Body(payload)                             // 设置请求体

	// 发送请求并获取响应
	resp, err := req.String()
	if err != nil {
		Error("HTTP 请求失败:", err)
		return err
	}

	// 打印响应结果
	Bot().Infof("转账确认请求成功，响应结果:", resp)

	// 解析响应
	var response struct {
		State     bool   `json:"state"`
		Error     string `json:"error"`
		Timestamp string `json:"timestamp"`
	}

	err = json.Unmarshal([]byte(resp), &response)
	if err != nil {
		Error("解析响应失败:", err)
		return err
	}

	// 检查响应状态
	if !response.State {
		Error("转账失败，原因:", response.Error)
		return fmt.Errorf("转账失败: %s", response.Error)
	}

	return nil
}



