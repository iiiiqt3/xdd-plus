func getFriends() {
	type AutoGenerated struct {
		ISRefersh int    `json:"is_refresh"`
		Token     string `json:"token"`
		RobotWxid string `json:"robot_wxid"`
		API       string `json:"api"`
	}

	req := httplib.Post(Config.Wx.Url)
	reply := &AutoGenerated{
		Token:     Config.Wx.Token,
		API:       "GetFriendlist",
		RobotWxid: Config.Wx.Robotid,
		ISRefersh: 0,
	}
	random := browser.Random()
	req.Header("User-Agent", random)
	marshal, _ := json.Marshal(reply)
	logs.Info(string(marshal))
	req.Body(string(marshal))
	s, _ := req.Bytes()
	list, _, _, _ := jsonparser.Get(s, "ReturnJson")
	jsonparser.ArrayEach(list, func(value []byte, dataType jsonparser.ValueType, offset int, err error) {
		var wxUser WxUser
		json.Unmarshal(value, &wxUser)
		db.Create(&wxUser)
	})
}
