package controllers

import (
	"encoding/json"
	browser "github.com/EDDYCJY/fake-useragent"
	"github.com/beego/beego/v2/client/httplib"
	"github.com/beego/beego/v2/core/logs"
)

type WxController struct {
	BaseController
}

func (c *WxController) HandleMessage() {
	data := c.Ctx.Input.RequestBody
	type AutoGenerated struct {
		SdkVer  int    `json:"sdkVer"`
		Event   string `json:"Event"`
		Content struct {
			RobotWxid     string `json:"robot_wxid"`
			Type          int    `json:"type"`
			FromGroup     string `json:"from_group"`
			FromGroupName string `json:"from_group_name"`
			FromWxid      string `json:"from_wxid"`
			FromName      string `json:"from_name"`
			Msg           string `json:"msg"`
			Clientid      int    `json:"clientid"`
			RobotType     int    `json:"robot_type"`
		} `json:"content"`
		// WsMCBreqID int `json:"wsMCBreqID"`
	}
	ag := &AutoGenerated{}
	err := json.Unmarshal(data, ag)
	logs.Info(err)
	logs.Info(data)

	logs.Info("接收到信息" + ag.Content.Msg)

	type AutoGenerated1 struct {
		Token     string `json:"token"`
		API       string `json:"api"`
		RobotWxid string `json:"robot_wxid"`
		ToWxid    string `json:"to_wxid"`
		Msg       string `json:"msg"`
	}
	req := httplib.Get("http://192.168.195.40:11150")
	reply := &AutoGenerated1{
		Token:     "1",
		API:       "SendTextMsg",
		RobotWxid: ag.Content.RobotWxid,
		ToWxid:    ag.Content.FromWxid,
		Msg:       ag.Content.Msg,
	}
	random := browser.Random()
	req.Header("User-Agent", random)
	marshal, _ := json.Marshal(reply)
	req.Body(marshal)
	s, _ := req.String()
	logs.Info(s)

}
